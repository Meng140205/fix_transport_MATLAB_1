addpath(fileparts(mfilename('fullpath')));
cache=dualarm.MpcStateCache();
stamp=struct('sec',int32(12),'nanosec',uint32(500000000));
cache.onClock(struct('clock',stamp));
names=[arrayfun(@(j)sprintf('left_joint%d',j),1:6,'UniformOutput',false),...
       arrayfun(@(j)sprintf('right_joint%d',j),1:6,'UniformOutput',false),...
       {'left_pgc140_finger1_joint','left_pgc140_finger2_joint',...
        'right_pgc140_finger1_joint','right_pgc140_finger2_joint'}];
joint=struct('header',struct('stamp',stamp),'name',{names},...
    'position',[ones(1,12),ones(1,4)*.01],...
    'velocity',zeros(1,16));
cache.onJoint(joint);
pose=struct('header',struct('stamp',stamp,'frame_id','default'),...
    'pose',struct('position',struct('x',0,'y',.3,'z',1.27),...
    'orientation',struct('x',0,'y',0,'z',0,'w',1)));
cache.onPose(pose);
status=struct('stamp',stamp,'mode',uint8(0),'state_valid',true,...
    'command_effort',zeros(6,1));
cache.onLeftStatus(status);cache.onRightStatus(status);
assert(cache.ready('rod'));
assert(abs(cache.rod(3,4)-1.27)<1e-12);
assert(all(abs(cache.fingers-.01)<1e-12));
fprintf('STATE_CACHE_PASS t=%.3f q=%d fingers=%d\n',...
    cache.simTime,numel(cache.q),numel(cache.fingers));

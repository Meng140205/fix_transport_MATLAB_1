function report=smoke_ros2_readonly(domainId)
%SMOKE_ROS2_READONLY Verify MATLAB ROS Toolbox receives simulation state.
% Requires ROS Toolbox and generated dualarm_mpc_msgs. No publishers exist.
if nargin<1,domainId=0;end
node=ros2node('matlab_mpc_readonly',domainId);
joint=ros2subscriber(node,'/joint_states','sensor_msgs/JointState',...
    'Reliability','besteffort');
rod=ros2subscriber(node,'/transport_rod/pose',...
    'geometry_msgs/PoseStamped','Reliability','besteffort');
left=ros2subscriber(node,'/dualarm_mpc/left_status',...
    'dualarm_mpc_msgs/ArmStatus','Reliability','reliable');
right=ros2subscriber(node,'/dualarm_mpc/right_status',...
    'dualarm_mpc_msgs/ArmStatus','Reliability','reliable');
clock=ros2subscriber(node,'/clock','rosgraph_msgs/Clock',...
    'Reliability','besteffort');
started=tic;
while toc(started)<10
    pause(.05);
    if ~isempty(joint.LatestMessage) && ~isempty(rod.LatestMessage) && ...
       ~isempty(left.LatestMessage) && ~isempty(right.LatestMessage) && ...
       ~isempty(clock.LatestMessage)
        break
    end
end
report=struct('joint',~isempty(joint.LatestMessage),...
    'rod',~isempty(rod.LatestMessage),...
    'left_status',~isempty(left.LatestMessage),...
    'right_status',~isempty(right.LatestMessage),...
    'clock',~isempty(clock.LatestMessage));
disp(report);
clear joint rod left right clock node
if ~all(struct2array(report))
    error('MATLAB did not receive all required ROS 2 state topics');
end
end
